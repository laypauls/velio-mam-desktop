/** invoke 실패를 `CommandError` 형태로 정규화한다. */
function normalize(e: unknown): CommandError {
  if (typeof e === "object" && e !== null && "code" in e && "message" in e) return e as CommandError
  // CommandError 가 아닌 거절(예: 인자 역직렬화 실패 문자열)은 사용자에게는 "알 수 없는 오류"로 보이므로 원본을 콘솔에 남긴다
  console.error("invoke rejected with a non-CommandError", e)
  return { code: "internal", message: typeof e === "string" ? e : "internal error" }
}

/** `ipc.ts` 래퍼의 reject 도 `CommandError` 로 정규화한다. */
function guard<T>(p: Promise<T>): Promise<T> {
  return p.catch((e: unknown) => {
    throw normalize(e)
  })
}

async function call<T>(cmd: string, args?: Record<string, unknown>): Promise<T> {
  try {
    return await invoke<T>(cmd, args)
  } catch (e) {
    throw normalize(e)
  }
}

